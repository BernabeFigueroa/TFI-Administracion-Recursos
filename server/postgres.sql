CREATE SCHEMA IF NOT EXISTS rtl;
REVOKE ALL ON SCHEMA rtl FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;
SET search_path TO rtl, extensions, public;

CREATE TABLE IF NOT EXISTS complexes(id TEXT PRIMARY KEY, data TEXT NOT NULL, created_order BIGINT GENERATED ALWAYS AS IDENTITY);
CREATE TABLE IF NOT EXISTS courts(id TEXT PRIMARY KEY, complex_id TEXT NOT NULL REFERENCES complexes(id), data TEXT NOT NULL, created_order BIGINT GENERATED ALWAYS AS IDENTITY, UNIQUE(id,complex_id));
CREATE TABLE IF NOT EXISTS admins(id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, complex_id TEXT NOT NULL REFERENCES complexes(id));
CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY, admin_id TEXT REFERENCES admins(id), expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS bookings(
  id TEXT PRIMARY KEY, complex_id TEXT NOT NULL, resource_id TEXT NOT NULL,
  owner_hash TEXT NOT NULL REFERENCES sessions(token_hash), date TEXT NOT NULL,
  start_min INTEGER NOT NULL CHECK(start_min>=0 AND start_min<1440),
  end_min INTEGER NOT NULL CHECK(end_min>start_min AND end_min<=1440),
  status TEXT NOT NULL CHECK(status IN ('confirmed','pending','cancelled')), data TEXT NOT NULL,
  FOREIGN KEY(resource_id,complex_id) REFERENCES courts(id,complex_id),
  CONSTRAINT booking_overlap EXCLUDE USING gist (
    resource_id WITH =, date WITH =, int4range(start_min,end_min,'[)') WITH &&
  ) WHERE (status!='cancelled')
);
CREATE INDEX IF NOT EXISTS booking_complex ON bookings(complex_id,date);
CREATE TABLE IF NOT EXISTS club_requests(id TEXT PRIMARY KEY, created_at TEXT NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS platform_admins(id TEXT PRIMARY KEY,email TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS platform_sessions(token_hash TEXT PRIMARY KEY,platform_admin_id TEXT NOT NULL REFERENCES platform_admins(id),expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS subscriptions(complex_id TEXT PRIMARY KEY REFERENCES complexes(id),plan TEXT NOT NULL CHECK(plan IN ('basic','pro','elite')),status TEXT NOT NULL CHECK(status IN ('active','trial','suspended')),paid_until TEXT NOT NULL,monthly_fee INTEGER NOT NULL CHECK(monthly_fee>=0),contact_email TEXT NOT NULL DEFAULT '',contact_phone TEXT NOT NULL DEFAULT '',updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS subscription_payments(id TEXT PRIMARY KEY,complex_id TEXT NOT NULL REFERENCES complexes(id),amount INTEGER NOT NULL CHECK(amount>0),paid_until TEXT NOT NULL,reference TEXT NOT NULL,created_at TEXT NOT NULL,actor TEXT NOT NULL,idempotency_key TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS reminders(id TEXT PRIMARY KEY,complex_id TEXT NOT NULL REFERENCES complexes(id),channel TEXT NOT NULL CHECK(channel IN ('email','whatsapp')),destination TEXT NOT NULL,message TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'draft' CHECK(status='draft'),created_at TEXT NOT NULL,actor TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS inventory(id TEXT PRIMARY KEY,complex_id TEXT NOT NULL REFERENCES complexes(id),name TEXT NOT NULL,price INTEGER NOT NULL CHECK(price>=0),stock INTEGER NOT NULL CHECK(stock>=0));
CREATE TABLE IF NOT EXISTS audit_log(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,complex_id TEXT REFERENCES complexes(id),action TEXT NOT NULL,actor TEXT NOT NULL DEFAULT 'Sistema',created_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'));
CREATE INDEX IF NOT EXISTS audit_complex ON audit_log(complex_id,id);
CREATE TABLE IF NOT EXISTS migration_history(id TEXT PRIMARY KEY,created_at TEXT NOT NULL,details TEXT NOT NULL);

CREATE OR REPLACE FUNCTION rtl.audit_booking() RETURNS trigger LANGUAGE plpgsql SET search_path=rtl,pg_temp AS $$
BEGIN
  IF current_setting('rtl.importing',true)='on' THEN RETURN NEW; END IF;
  INSERT INTO audit_log(complex_id,action) VALUES(NEW.complex_id,
    CASE WHEN TG_OP='INSERT' THEN 'Reserva creada: ' WHEN NEW.status='cancelled' THEN 'Reserva cancelada: ' ELSE 'Reserva actualizada: ' END || NEW.id);
  RETURN NEW;
END;
$$;
CREATE OR REPLACE FUNCTION rtl.audit_court() RETURNS trigger LANGUAGE plpgsql SET search_path=rtl,pg_temp AS $$
BEGIN
  IF current_setting('rtl.importing',true)='on' THEN RETURN NEW; END IF;
  INSERT INTO audit_log(complex_id,action) VALUES(NEW.complex_id,'Cancha actualizada: '||NEW.id);
  RETURN NEW;
END;
$$;
DO $$ BEGIN
  IF NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgname='audit_booking_change' AND tgrelid='rtl.bookings'::regclass) THEN
    CREATE TRIGGER audit_booking_change AFTER INSERT OR UPDATE ON rtl.bookings FOR EACH ROW EXECUTE FUNCTION rtl.audit_booking();
  END IF;
  IF NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgname='audit_court_change' AND tgrelid='rtl.courts'::regclass) THEN
    CREATE TRIGGER audit_court_change AFTER UPDATE ON rtl.courts FOR EACH ROW EXECUTE FUNCTION rtl.audit_court();
  END IF;
END $$;
DO $$ DECLARE tab RECORD; BEGIN
  FOR tab IN SELECT tablename FROM pg_tables WHERE schemaname='rtl' LOOP
    EXECUTE format('ALTER TABLE rtl.%I ENABLE ROW LEVEL SECURITY',tab.tablename);
    EXECUTE format('REVOKE ALL ON TABLE rtl.%I FROM PUBLIC',tab.tablename);
  END LOOP;
END $$;
